const DICT: Record<Lang, Record<string, string>> = { th: TH, en: EN };

export type Lang = "th" | "en";

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nCtx = createContext<I18nValue>({ lang: "th", setLang: () => {}, t: (k) => k });

/** Missing keys are reported once so translations can be completed. */
const missing = new Set<string>();
function lookup(lang: Lang, key: string): string | undefined {
  const v = DICT[lang][key] ?? DICT.en[key];
  if (v === undefined && !missing.has(key)) {
    missing.add(key);
    if (import.meta.env?.DEV) console.warn(`[i18n] missing '${key}' (${lang})`);
  }
  return v;
}

/** Current language, readable outside React (store, toasts). */
let currentLang: Lang = (localStorage.getItem("adbstudio.lang") as Lang) ?? "th";

/** Translate outside components — same dictionaries, current language. */
export function translate(key: string, vars?: Record<string, string | number>): string {
  const v = lookup(currentLang, key) ?? key;
  if (!vars) return v;
  let out = v;
  for (const [k, val] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(val));
  return out;
}

export function setTranslateLang(l: Lang): void { currentLang = l; }
export function getTranslateLang(): Lang { return currentLang; }

export function I18nProvider({ children }: { children: ReactNode }) {
  // #lang=th|en (used by smoke captures) wins, then the stored preference, then Thai
  const [lang, setLangState] = useState<Lang>(() => {
    const fromHash = new URLSearchParams(location.hash.replace(/^#/, "")).get("lang");
    if (fromHash === "th" || fromHash === "en") return fromHash;
    return (localStorage.getItem("adbstudio.lang") as Lang) || "th";
  });

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("adbstudio.lang", l);
    document.documentElement.lang = l;
  }, []);

  useEffect(() => { setTranslateLang(lang); }, [lang]);

  const t = useCallback((key: string, vars?: Record<string, string | number>) => {
    let s = lookup(lang, key) ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n(): I18nValue { return useContext(I18nCtx); }

